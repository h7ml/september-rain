import type * as Three from 'three'

/**
 * 世界层契约：第一人称可探索场景。
 *
 * ## 与 `lib/scene/` 的关系
 *
 * `lib/scene/` 是旧的 2D 剪影场景系统（窄条画幅 + 归一化坐标 + 粒子配方），
 * 它服务的是「一屏里看一片雨」。这里是它的继任者：一个**有尺度的三维空间**，
 * 玩家用第一人称走进去。
 *
 * 两者共享的不是代码，而是三条设计意图：
 * 1. 骨架统一负责生命周期，场景模块只做声明——否则会有 N 份 WebGL 回收 bug。
 * 2. 所有随机量走 `createRandom(seed)`，同一场景每次进入必须一模一样。
 * 3. 内容用「声明式配方」描述，运行时细节留给骨架。
 *
 * ## 单位约定
 *
 * - 长度：**米**。玩家眼高 1.68m，走一步约 0.9m，看台高 1.2m。
 *   旧系统用「画幅百分比」，这里必须换成真实尺度——第一人称下
 *   错误的尺度会立刻表现为晕眩（步子太大像飘，太小像爬）。
 * - 角度：**弧度**。`yaw` 绕 Y 轴（左右转头，无限制），
 *   `pitch` 绕 X 轴（上下抬头，钳制在 ±85°）。允许 ±90° 会导致万向节问题，
 *   且抬头看天顶时画面会翻转。
 * - 速度：米/秒。步行 3.2m/s 接近真人，跑步 5.4m/s。
 */

/* ------------------------------------------------------------------ *
 * 玩家
 * ------------------------------------------------------------------ */

/** 玩家状态。位置是**脚底**在地面上的点，不是眼睛——移动与碰撞都在脚底平面上算。 */
export type PlayerState = {
  x: number
  z: number
  /** 视线方向，弧度 */
  yaw: number
  pitch: number
}

/** 玩家的物理尺寸与运动参数。 */
export type PlayerConfig = {
  /** 眼高（米）。脚底到视点。 */
  eyeHeight: number
  /** 碰撞半径（米）。第一人称下取 0.35 左右，太大会卡在门框上。 */
  radius: number
  /** 步行速度（米/秒） */
  walkSpeed: number
  /** 跑步速度（米/秒），按住 Shift 时生效 */
  runSpeed: number
  /** 加速阻尼（每秒趋近比例，0-1）。1 为瞬时起步，手感会「僵硬」。 */
  acceleration: number
  /** 转向灵敏度（弧度/像素）。指针锁定下这是鼠标位移到角度的换算比。 */
  lookSensitivity: number
}

/* ------------------------------------------------------------------ *
 * 碰撞
 * ------------------------------------------------------------------ */

/**
 * 碰撞体：只用两种基本形。
 *
 * 取舍：不做真实网格碰撞（需要物理引擎与凸包分解），也不做地形高度场
 * （诗人剪影风里没有起伏地形）。AABB 管建筑与围墙，圆柱管树干与灯柱，
 * 足够表达「操场、教学楼、银杏路、城墙」这些空间的边界。
 * 玩家统一按圆柱（半径 `radius`）处理，与这两者的碰撞都是圆-面/圆-圆。
 */
export type Collider =
  /** 轴对齐盒体。`x`/`z` 是中心，`halfX`/`halfZ` 是半宽。 */
  | { kind: 'box'; x: number; z: number; halfX: number; halfZ: number }
  /** 圆柱体。`radius` 是截面半径。 */
  | { kind: 'cylinder'; x: number; z: number; radius: number }

/* ------------------------------------------------------------------ *
 * 交互
 * ------------------------------------------------------------------ */

/** 世界坐标里的一个点。 */
export type Vec3 = { x: number; y: number; z: number }

/**
 * 可交互热点：场景里能被「看着并点击」的东西。
 *
 * 设计取舍：热点的**可视化对象**（那封信、那个邮筒、那个雨伞）
 * 由场景模块自己建成 three.js 对象并挂到 `object` 上，
 * 骨架只负责射线拾取与提示。
 *
 * 为什么不给每种热点写一个 kind：第一版只需要「一个能点的东西」，
 * 一旦引入 kind 就会长出一堆分支（kind 决定图标、音效、动效……），
 * 而那些差异其实都应该由场景模块通过 `object` 自己表达。
 */
export type Hotspot = {
  id: string
  /** 用于拾取与视觉高亮的 three.js 对象。必须已加入场景图。 */
  object: Three.Object3D
  /** 准星对准时显示的一行提示，例如「看台上的白裙子」。 */
  label: string
  /**
   * 触发所需的最大距离（米）。超出后不显示提示、不可拾取。
   * 不设默认值：距离是这个游戏里最重要的叙事工具之一——
   * 「只能远远看着」和「可以走近」是两种完全不同的情绪。
   *
   * **量法是从眼睛量起的三维距离**（即 `RayHit.distance`），不是水平步行距离。
   * 眼高约 1.68m，所以一个放在地面上的东西，`reach: 2` 实际只允许你走到
   * 水平方向约 1.1m 处。给地面物件标距离时要按这个尺度给，否则会出现
   * 「看着就在脚边却点不到」。
   */
  reach: number
  /** 被点击时调用。返回 `true` 表示这次点击已被消费（通常意味着要弹叙事层）。 */
  onActivate: () => boolean | void
}

/**
 * 触发区域：走进就发生的事，不需要点击。
 *
 * 与 `Hotspot` 的分工：`Hotspot` 是「主动看，主动点」，
 * `TriggerZone` 是「走到这里，故事自己发生」。前者用于回忆碎片，
 * 后者用于推进剧情——玩家不该为了「继续故事」去找一个按钮。
 *
 * `once` 默认 `true`：重复触发会让玩家在往返时被同一个事件反复打断。
 */
export type TriggerZone = {
  id: string
  x: number
  z: number
  radius: number
  /** 离开区域后能否再次触发。默认 `false`（只触发一次）。 */
  repeatable?: boolean
  onEnter: () => boolean | void
}

/** 一次射线拾取的结果。 */
export type RayHit = {
  /** 命中的热点 id */
  id: string
  /** 命中点到相机的距离（米） */
  distance: number
}

/* ------------------------------------------------------------------ *
 * 场景模块
 * ------------------------------------------------------------------ */

/** 场景可读的运行时上下文。 */
export type SceneRuntime = {
  three: typeof Three
  /** 场景根节点。模块加进来的东西都会被自动回收。 */
  root: Three.Group
  /** 该场景的确定性随机源。同一 `seed` 必须生成同一片雨。 */
  random: import('../scene/random').Random
  /** 当前视口的宽高比，用于按比例布景。 */
  aspect: number
}

/** 一个可探索空间。 */
export type WorldScene = {
  id: string
  /** 进入场景时显示的一行地点名，例如「西安 · 军训操场」。 */
  caption: string
  /** 固定种子：同一场景每次进入必须完全相同。 */
  seed: number
  /**
   * 建场景。模块在这里把几何体、灯光、粒子加进 `root`，
   * 返回可选的逐帧更新函数。
   *
   * 骨架负责：相机、渲染器、雾的全局调参、回收、以及玩家与交互。
   * 模块负责：这片空间长什么样、有什么可点的、走到哪里发生什么。
   */
  build: (runtime: SceneRuntime) => WorldSceneHandle
}

/** `build` 的产物。骨架持有它，负责逐帧推进与回收。 */
export type WorldSceneHandle = {
  /**
   * 逐帧调用。`delta` 是距上一帧的秒数（已钳制，不会出现大跳）。
   *
   * 骨架传入 `player` 的只读快照，让场景能做「玩家走近时灯变亮」
   * 这类反应；场景**不得**修改它——移动的唯一入口是玩家控制器。
   */
  update?: (elapsed: number, delta: number, player: Readonly<PlayerState>) => void
  /** 窗口尺寸变化。参数是视口宽高比。 */
  resize?: (aspect: number) => void
  /** 本场景的碰撞体。骨架用它与玩家做圆-面/圆-圆求交。 */
  colliders?: Collider[]
  /**
   * 会遮挡视线的实体，供交互系统做"看得见才点得到"的判定。
   *
   * 为什么不从 `colliders` 自动派生：`Collider` 是**纯二维**的（只有 x/z 与半宽），
   * 没有高度信息。看台 1.2m 和围墙 2.5m 若按同一假设高度生成代理盒，
   * 必然有一方是错的——矮看台会挡住本该看见的东西，高围墙反而挡不住。
   * 所以由场景模块显式交出"哪些网格挡视线"，它与模块自己的几何体同源，不会失配。
   *
   * 留空表示本场景不做遮挡判定（代价是隔着墙也能点击）。
   */
  occluders?: Three.Object3D[]
  /** 本场景的可交互热点。 */
  hotspots?: Hotspot[]
  /** 本场景的触发区域。 */
  triggers?: TriggerZone[]
  /**
   * 场景自己判断"叙事闸门已满足"时调用它，通知宿主可以显示选项了。
   *
   * 为什么需要这个而不是让宿主监听 `triggers`：闸门的满足条件常常
   * **不等于**走进某个区域。第一幕里「走到操场中央」是个触发器，
   * 但也可能写成"走近看台且抬头看了一会儿"这种复合条件——
   * 那种判断只有场景模块做得了。宿主不该去理解每个场景的推进规则。
   *
   * 宿主在拿到 `build` 的返回值后把回调赋上去；场景模块在条件满足时调用。
   */
  onGateSatisfied?: () => void
}

/* ------------------------------------------------------------------ *
 * 骨架对外接口
 * ------------------------------------------------------------------ */

/**
 * 每帧向宿主回报的状态。宿主（React）据此更新准星提示与叙事层，
 * 但**不参与逐帧渲染**——这是刻意设计：把逐帧状态灌进 React state
 * 会每秒触发几十次重渲染，在第一人称下直接表现为掉帧。
 */
export type WorldFrameState = {
  /** 准星当前对准的热点 id，未对准为 `null`。只在**变化时**回报。 */
  focusedHotspotId: string | null
  /**
   * 该热点的展示文案，直接来自 `Hotspot.label`，未对准为 `null`。
   *
   * 为什么由骨架回报而不是让宿主自己查表：`label` 是**场景数据**，
   * 写在每个场景模块里。若宿主再维护一份 id → 文案的映射，
   * 那条映射会在每次新增场景时落后一步，而失效的表现只是"准星不显示提示"——
   * 一个不报错、只能靠人眼发现的静默缺陷。走这条链就不存在第二份真相。
   */
  focusedHotspotLabel: string | null
  /**
   * 玩家是否被指针锁定捕获。`false` 时应显示「点击进入场景」引导，
   * 并停止接收鼠标转向（但仍可渲染）。
   */
  locked: boolean
}

/** 世界骨架的句柄。宿主拿它控制玩家的出生点与暂停。 */
export type WorldHandle = {
  /** 平滑地把玩家移到指定位置与朝向（用于场景切换后的落点）。 */
  placePlayer: (state: Partial<PlayerState>) => void
  /** 读取当前玩家状态的快照。 */
  getPlayer: () => PlayerState
  /** 暂停逐帧更新（不销毁资源）。用于打开全屏叙事面板时。 */
  setPaused: (paused: boolean) => void
  /**
   * 请求进入指针锁定（第一人称）。
   *
   * **必须在用户手势的调用栈里同步调用**——浏览器的自动播放类策略会检查
   * 调用来源，异步（`setTimeout`、`await` 之后）发起会被静默拒绝，
   * 而且不报错，表现为「点了没反应」。
   *
   * 触屏设备没有指针锁定，实现应视为空操作；那些设备上引导层本就不出现
   * （`locked` 初始即为真）。
   */
  requestPointerLock: () => void
  /** 手动触发一次拾取（用于触屏端点击）。命中返回 `true`。 */
  activateAtCenter: () => boolean
  /** 彻底销毁：释放几何体、材质、纹理与 WebGL 上下文。 */
  dispose: () => void
}

/** 世界骨架的构造参数。 */
export type WorldConfig = {
  /** 挂载点。骨架会在此创建 canvas。 */
  host: HTMLElement
  /** 场景模块。切换场景时由宿主重建骨架，或由骨架提供热切换（见实现说明）。 */
  scene: WorldScene
  player: Partial<PlayerConfig>
  /** 逐帧回报。实现在调用前必须去重，不要每帧都回调。 */
  onFrame?: (state: WorldFrameState) => void
  /**
   * 场景模块判定「叙事闸门已满足」时回调。
   *
   * 骨架只做转接：它在 `build` 之后把这里收到的回调赋给场景句柄的
   * `onGateSatisfied`（那个字段的说明见 `WorldSceneHandle`）。
   *
   * 为什么不让宿主自己去拿场景句柄来赋值：`WorldSceneHandle` 是骨架的内部产物，
   * 宿主拿不到，也不该拿到——一旦暴露，宿主就会开始读 `colliders`、`hotspots`
   * 去自己实现拾取与碰撞，骨架与宿主的职责立刻就糊了。
   * 宿主要知道的只有一件事：闸门开了。
   */
  onGate?: () => void
}
