/**
 * 《蒹葭》主线故事图。
 *
 * ## 改编原则
 *
 * 素材是 `public/store.txt` 里的真实回忆散文，版权归原作者。这份图做的是
 * **互动编排**：把原文已经存在的分叉（那些"如果当时"）显式化为可选择的路，
 * 而不是替作者续写他没写的人生。
 *
 * 三条自律：
 * 1. **原文的关键句不动**。「只有她回了一个字：我」「你自己打个车吧」
 *    「原来，那是倒计时」——这些是故事的骨头，改编不能碰。
 * 2. **玩家能改变的只有"表达"，不能改变"事实"**。分手、等待、错过都发生了，
 *    这正是原作的重量所在。玩家改变的是他是否说出口、是否看见、是否放手，
 *    而这些决定了结局的**语气**，不决定事件的**有无**。
 * 3. **不编造和解**。没有"追回来"这种选项——原文里没有，编出来是对素材的轻慢。
 *    最好的结局也只是「把自己放回人生中心」，不是「她回来了」。
 *
 * ## 图的结构
 *
 * ```
 *   m01 看台 ──► m02 一个字 ──┬──► r01 靠近（approach 路线）
 *                            └──► r02 远远看着（hold-back 路线）
 *                                     │
 *   r01/r02 ──► s01 六年 ──► s02 上海两个月 ──► s03 出国前
 *                                                  │
 *   s03 ──► f01 时差 ──► f02 多瑙河 ──► f03 火锅 ──► f04 机场
 *                                                       │
 *   f04 ──► e01 楼梯间 ──► e02 城墙根 ──► 结局判定
 * ```
 *
 * 中段（m02）真正分叉，s01 合流——因为"六年"和"疫情"这两段是不可抗的，
 * 无论走哪条路都会发生。分叉影响的是玩家的变量，变量影响结局语气。
 */

